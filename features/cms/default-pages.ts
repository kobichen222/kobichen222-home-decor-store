import type { StoreSettings } from "./queries";

type Business = StoreSettings["business"];

/**
 * Built-in text for pages the law requires, used until the store creates a
 * page with the same address in the admin (which then replaces this).
 * Written in the RichText format; business details are filled in from the
 * store settings.
 */
export function defaultPage(slug: string, b: Business): { title: string; description: string; body: string } | null {
  const name = b.name || "החנות";
  const contact = [b.email && `דוא״ל: ${b.email}`, b.phone && `טלפון: ${b.phone}`, b.address && `כתובת: ${b.address}`].filter(Boolean).map((l) => `- ${l}`).join("\n");
  const updated = "נובמבר 2026";

  if (slug === "privacy") {
    return {
      title: "מדיניות פרטיות",
      description: `איזה מידע ${name} אוסף, למה, ואיך הוא נשמר.`,
      body: `עודכן לאחרונה: ${updated}

הפרטיות שלכם חשובה לנו. מסמך זה מסביר איזה מידע ${name} אוספת כשאתם משתמשים באתר, למה, עם מי הוא משותף, ומה הזכויות שלכם. המדיניות נכתבה בהתאם לחוק הגנת הפרטיות, התשמ״א-1981, ולתקנות שהותקנו מכוחו.

## איזה מידע אנחנו אוספים
- **פרטי הזמנה:** שם, טלפון, דוא״ל, כתובת למשלוח, ופרטי חברה ללקוחות עסקיים.
- **פרטי חשבון:** אם נרשמתם, גם הסיסמה (שמורה מוצפנת), כתובות שמורות ורשימת מועדפים.
- **פניות:** מה שכתבתם בטופס יצירת קשר, בבקשת הצעת מחיר או בחוות דעת.
- **פרטי תשלום:** התשלום מבוצע אצל חברת סליקה מורשית. **פרטי כרטיס האשראי אינם עוברים דרכנו ואינם נשמרים אצלנו.**
- **מידע טכני:** כתובת IP, סוג הדפדפן והמכשיר ועמודים שנצפו. זה משמש לאבטחה, למניעת הונאות ולתפעול האתר.

## למה אנחנו משתמשים במידע
- כדי לבצע את ההזמנה, לשלוח אותה ולעדכן אתכם על מצבה.
- כדי לתת שירות ולענות לפניות.
- כדי לעמוד בחובות לפי דין, למשל הנהלת חשבונות.
- כדי לשלוח עדכונים ומבצעים, **רק אם הסכמתם לכך**. אפשר להסיר את ההסכמה בכל עת.

## עוגיות (Cookies) וכלי מדידה
האתר משתמש בעוגיות הכרחיות, למשל כדי לשמור את סל הקניות ואת ההתחברות. כלי מדידה ושיווק, כמו Google Analytics או Meta Pixel, מופעלים רק אחרי שאישרתם זאת בהודעת העוגיות.

## עם מי המידע משותף
אנחנו לא מוכרים מידע אישי. אנחנו משתפים אותו רק עם ספקים שעוזרים לנו להפעיל את החנות, ורק במידה הנדרשת:
- חברת הסליקה, לביצוע התשלום.
- חברת השילוח, לצורך המשלוח.
- ספקי אחסון, שליחת דוא״ל ותוכנת הנהלת חשבונות.
- רשויות, כאשר החוק מחייב זאת.
חלק מהספקים שומרים מידע בשרתים מחוץ לישראל, בכפוף להגנות מקובלות.

## כמה זמן המידע נשמר
פרטי הזמנות נשמרים כל עוד הדבר נדרש לצורכי שירות, אחריות והנהלת חשבונות לפי דין. מידע שאינו נדרש עוד נמחק.

## אבטחת מידע
האתר מוצפן (HTTPS) והגישה למידע מוגבלת לעובדים שצריכים אותה, עם הרשאות ואימות דו־שלבי. אין אבטחה מושלמת, אבל אנחנו נוקטים אמצעים סבירים ומקובלים כדי להגן על המידע.

## הזכויות שלכם
אתם זכאים לעיין במידע שנשמר עליכם, לבקש לתקן אותו או למחוק אותו, ולבקש להסיר אתכם מרשימת הדיוור. לשם כך פנו אלינו בפרטים שבהמשך, ונטפל בבקשה תוך זמן סביר.

## יצירת קשר בנושא פרטיות
${contact || "- דרך [עמוד יצירת הקשר](/contact)"}

ייתכן שנעדכן מדיניות זו מעת לעת. הנוסח המחייב הוא זה שמופיע באתר.`,
    };
  }

  if (slug === "accessibility") {
    return {
      title: "הצהרת נגישות",
      description: `הנגשת האתר של ${name} לאנשים עם מוגבלות.`,
      body: `עודכן לאחרונה: ${updated}

${name} רואה חשיבות בכך שכל אדם, כולל אנשים עם מוגבלות, יוכל לגלוש באתר ולהזמין בו בקלות ובעצמאות. ההנגשה נעשתה בהתאם לחוק שוויון זכויות לאנשים עם מוגבלות, התשנ״ח-1998, ולתקנות הנגישות לשירות (תקנה 35).

## רמת הנגישות
האתר הונגש לפי התקן הישראלי ת״י 5568, שמבוסס על הנחיות WCAG 2.1, ברמה AA.

## מה עשינו באתר
- ניווט מלא במקלדת, כולל תפריטים, חלונות קופצים וסל הקניות, וקישור "דילוג לתוכן הראשי".
- מבנה כותרות ותגיות שמתאים לקוראי מסך, ותיאור טקסטואלי לתמונות ולכפתורים.
- ניגודיות צבעים לפי התקן, וטקסט שאפשר להגדיל בדפדפן בלי לאבד תוכן.
- התאמה מלאה לטלפונים ולטאבלטים.
- טפסים עם תוויות ברורות והודעות שגיאה שמוקראות לקוראי מסך.
- כיבוי אנימציות למי שהגדיר במכשיר "הפחתת תנועה".
- בדיקה תקופתית בכלי בדיקה אוטומטיים ובבדיקה ידנית.

## מגבלות ידועות
למרות מאמצינו, ייתכן שחלקים מסוימים עדיין אינם נגישים במלואם, למשל תוכן של צד שלישי או סרטונים שהועלו בלי כתוביות. אנחנו ממשיכים לשפר.

## נתקלתם בבעיה?
נשמח לשמוע ולתקן. כתבו לנו מה הבעיה ובאיזה עמוד, ונחזור אליכם בהקדם:
${contact || "- דרך [עמוד יצירת הקשר](/contact)"}`,
    };
  }
  return null;
}
